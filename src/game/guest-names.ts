// Guest names come in four shapes:
// - an adjective and a noun: "WonderfulCat", "GatoMaravilhoso", "GatoMaravilloso",
//   "すてきなネコ";
// - two nouns, a hybrid: "PotatoNinja", "BatataNinja", "PapaNinja", "ジャガイモ忍者";
// - a title and a noun, the title following the noun's Portuguese gender in every
//   language: "QueenFox", "RainhaRaposa", "ReinaZorro", "キツネ女王"; a title with a
//   different word for each gender in every language also comes in the other one:
//   "QueenCat", "RainhaGato";
// - now and then, a legendary meme name: "TGIF", "Sextou", "YaEsViernes", "花金".
// Each row holds the same idea in every language, so the same guest number gives the
// same name, translated, to everyone in a room (whatever language each one plays in).
// Words are friendly or playfully silly, never insults; nouns avoid ones that are slurs
// or double meanings in Portuguese (vaca, anta, galinha, macaco...) or Spanish (zorra,
// mariquita...). Spanish is neutral Latin American.

/** [English, Portuguese masculine, Portuguese feminine, Japanese (attributive form), Spanish masculine, Spanish feminine]. */
type Adjective = readonly [
  en: string,
  ptM: string,
  ptF: string,
  ja: string,
  esM: string,
  esF: string,
];
/** [English, Portuguese, its grammatical gender, Japanese, Spanish, its grammatical gender]. */
type Noun = readonly [
  en: string,
  pt: string,
  gender: "m" | "f",
  ja: string,
  es: string,
  esGender: "m" | "f",
];
/** Masculine and feminine: [English, English, Portuguese, Portuguese, Japanese suffix, Japanese suffix, Spanish, Spanish]. */
type Title = readonly [
  enM: string,
  enF: string,
  ptM: string,
  ptF: string,
  jaM: string,
  jaF: string,
  esM: string,
  esF: string,
];
/** [English, Portuguese, Japanese, Spanish]: the meme, or its local twin where one exists. */
type Legendary = readonly [en: string, pt: string, ja: string, es: string];

