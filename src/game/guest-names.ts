/** Titles that also stand alone in Japanese, after an adjective: not さん, ちゃん, くん or 殿. */
const STANDALONE_TITLES = TITLES.filter(
  ([, , , , ja]) => !["さん", "ちゃん", "くん", "殿"].includes(ja),
);

/** Titles with a different word for each gender in every language ("King", "Queen"). */
const GENDERED_TITLES = TITLES.filter(
  ([enM, enF, ptM, ptF, jaM, jaF, esM, esF]) =>
    enM !== enF && ptM !== ptF && jaM !== jaF && esM !== esF,
);

// Guest numbers run through the shapes in order: adjective and noun, hybrids, title and
// noun, the legendary names, title and adjective, then gendered titles and nouns in the
// other gender (each added last, so older numbers keep their names).
const ADJECTIVE_NOUNS = ADJECTIVES.length * NOUNS.length;
const HYBRIDS = NOUNS.length * NOUNS.length;
const TITLED = TITLES.length * NOUNS.length;
const LEGENDARY_START = ADJECTIVE_NOUNS + HYBRIDS + TITLED;
const TITLED_ADJECTIVES = STANDALONE_TITLES.length * ADJECTIVES.length;
const CROSS_TITLED = GENDERED_TITLES.length * NOUNS.length;
export const GUEST_NAME_COUNT =
  LEGENDARY_START + LEGENDARY.length + TITLED_ADJECTIVES + CROSS_TITLED;

/** A noun in a language. */
const nounIn = ([en, pt, , ja, es]: Noun, lang: Lang) =>
  lang === "pt" ? pt : lang === "es" ? es : lang === "ja" ? ja : en;

/** A title and a noun, the title in the given gender. */
function titled(title: Title, noun: Noun, f: boolean, lang: Lang): string {
  const [enM, enF, ptM, ptF, jaM, jaF, esM, esF] = title;
  const word = nounIn(noun, lang);
  if (lang === "pt") return (f ? ptF : ptM) + word;
  if (lang === "es") return (f ? esF : esM) + word;
  if (lang === "ja") return word + (f ? jaF : jaM);
  return (f ? enF : enM) + word;
}

/**
 * A guest's name from their guest number, written as one word.
 * Adjective and noun: English and Japanese put the adjective first ("WonderfulCat",
 * "すてきなネコ"); Portuguese and Spanish put the noun first and agree in gender
 * ("GatoMaravilhoso", "RaposaMaravilhosa", "RanaMaravillosa"), each with its own
 * noun's gender ("ZorroMaravilloso").
 * Hybrid: two nouns in the same order everywhere ("PotatoNinja", "BatataNinja").
 * Title and noun: the title first, last in Japanese ("QueenFox", "RainhaRaposa",
 * "ReinaZorro", "キツネ女王"). Its gender follows the noun's Portuguese one in every
 * language; gendered titles also come in the other one ("QueenCat", "RainhaGato",
 * "ネコ女王").
 * Title and adjective: the same order, the adjective first in Japanese ("CaptainBrave",
 * "CapitãoCorajoso", "勇敢な船長"). With no noun to give a gender, half the pairs are
 * masculine and half feminine; both would read the same in English.
 */
export function guestName(guestNumber: number, lang: Lang): string {
  let i = Math.abs(Math.trunc(guestNumber) || 0) % GUEST_NAME_COUNT;
  if (i < ADJECTIVE_NOUNS) {
    const [en, ptM, ptF, ja, esM, esF] = ADJECTIVES[i % ADJECTIVES.length];
    const noun = NOUNS[Math.floor(i / ADJECTIVES.length)];
    const [, , gender, , , esGender] = noun;
    const word = nounIn(noun, lang);
    if (lang === "pt") return word + (gender === "f" ? ptF : ptM);
    if (lang === "es") return word + (esGender === "f" ? esF : esM);
    if (lang === "ja") return ja + word;
    return en + word;
  }
  i -= ADJECTIVE_NOUNS;
  if (i < HYBRIDS) {
    return (
      nounIn(NOUNS[Math.floor(i / NOUNS.length)], lang) +
      nounIn(NOUNS[i % NOUNS.length], lang)
    );
  }
  i -= HYBRIDS;
  if (i < TITLED) {
    const noun = NOUNS[Math.floor(i / TITLES.length)];
    return titled(TITLES[i % TITLES.length], noun, noun[2] === "f", lang);
  }
  i -= TITLED;
  if (i < LEGENDARY.length) {
    const [en, pt, ja, es] = LEGENDARY[i];
    return lang === "pt" ? pt : lang === "es" ? es : lang === "ja" ? ja : en;
  }
  i -= LEGENDARY.length;
  if (i >= TITLED_ADJECTIVES) {
    i -= TITLED_ADJECTIVES;
    const noun = NOUNS[Math.floor(i / GENDERED_TITLES.length)];
    // the other gender than the noun's
    const title = GENDERED_TITLES[i % GENDERED_TITLES.length];
    return titled(title, noun, noun[2] === "m", lang);
  }
  const t = i % STANDALONE_TITLES.length;
  const a = Math.floor(i / STANDALONE_TITLES.length);
  const [enM, enF, ptM, ptF, jaM, jaF, esM, esF] = STANDALONE_TITLES[t];
  const [en, adjPtM, adjPtF, ja, adjEsM, adjEsF] = ADJECTIVES[a];
  const f = (t + a) % 2 === 1;
  if (lang === "pt") return f ? ptF + adjPtF : ptM + adjPtM;
  if (lang === "es") return f ? esF + adjEsF : esM + adjEsM;
  if (lang === "ja") return ja + (f ? jaF : jaM);
  return (f ? enF : enM) + en;
}

/**
 * The name a reader sees: an account's own, else the guest name in the
 * reader's language. Only the server calls it: the browser gets names ready.
 */
export const displayName = (
  p: { isGuest: boolean; name: string | null; guestNumber: number },
  lang: Lang,
) => (!p.isGuest && p.name ? p.name : guestName(p.guestNumber, lang));

/** Longest name allowed per language (in characters), so names fit the player strip. */
export const GUEST_NAME_MAX: Record<Lang, number> = {
  en: 18,
  pt: 18,
  es: 18,
  ja: 10,
};

const fits = (n: number) =>
  LANGS.every((l) => [...guestName(n, l)].length <= GUEST_NAME_MAX[l]);

/** How often a new guest gets a legendary name. */
export const LEGENDARY_CHANCE = 1 / 100;

/** A random guest number whose name is short enough in every language; now and then a legendary one. */
export function randomGuestNumber(random: () => number = Math.random): number {
  if (random() < LEGENDARY_CHANCE)
    return LEGENDARY_START + Math.floor(random() * LEGENDARY.length);
  let n = 0;
  for (let tries = 0; tries < 100; tries++) {
    // every number but the legendary ones
    n = Math.floor(random() * (GUEST_NAME_COUNT - LEGENDARY.length));
    if (n >= LEGENDARY_START) n += LEGENDARY.length;
    if (fits(n)) return n;
  }
  return n;
}
